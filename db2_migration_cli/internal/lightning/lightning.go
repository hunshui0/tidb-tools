func ResolveDataPath(value string) (string, error) {
	if strings.Contains(value, "://") {
		return value, nil
	}
	if len(value) >= 3 && ((value[0] >= 'A' && value[0] <= 'Z') || (value[0] >= 'a' && value[0] <= 'z')) && value[1] == ':' && (value[2] == '\\' || value[2] == '/') {
		value = "/mnt/" + strings.ToLower(string(value[0])) + "/" + strings.ReplaceAll(value[3:], "\\", "/")
		// Keep WSL paths in Linux form even when generating TOML on Windows.
		return path.Clean(value), nil
	}
	return filepath.Abs(value)
}

func Create(path, dataDir, host string, port int, user, password string, statusPort int, backend, pdAddr, sortedKVDir, logFile string, force bool) (string, error) {
	if dataDir == "" {
		return "", errors.New("--data-dir is required")
	}
	if backend != "tidb" && backend != "local" {
		return "", errors.New("--backend must be tidb or local")
	}
	if port < 1 || port > 65535 || statusPort < 1 || statusPort > 65535 {
		return "", errors.New("ports must be between 1 and 65535")
	}
	if backend == "local" && (pdAddr == "" || sortedKVDir == "") {
		return "", errors.New("the local backend requires --pd-addr and --sorted-kv-dir")
	}
	resolvedData, err := ResolveDataPath(dataDir)
	if err != nil {
		return "", err
	}
	if sortedKVDir != "" {
		sortedKVDir, err = ResolveDataPath(sortedKVDir)
		if err != nil {
			return "", err
		}
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		return "", err
	}
	if !force {
		if _, err := os.Stat(abs); err == nil {
			return "", fmt.Errorf("%s already exists (use --force to overwrite)", abs)
		} else if !errors.Is(err, os.ErrNotExist) {
			return "", err
		}
	}
	if err := os.MkdirAll(filepath.Dir(abs), 0755); err != nil {
		return "", err
	}
	if err := os.WriteFile(abs, []byte(BuildConfig(resolvedData, host, port, user, password, statusPort, backend, pdAddr, sortedKVDir, logFile)), 0600); err != nil {
		return "", err
	}
	return abs, nil
}

func BuildConfig(dataDir, host string, port int, user, password string, statusPort int, backend, pdAddr, sortedKVDir, logFile string) string {
	q := strconv.Quote
	var b strings.Builder
	b.WriteString("# Generated by db2-migrate. Edit this TiDB Lightning task configuration before production use.\n\n")
	b.WriteString("[lightning]\nstatus-addr = \":8289\"\nserver-mode = false\ncheck-requirements = true\nindex-concurrency = 2\ntable-concurrency = 6\nlevel = \"info\"\nfile = " + q(logFile) + "\nmax-size = 128\nmax-days = 28\nmax-backups = 14\n\n")
	b.WriteString("[security]\nca-path = \"\"\ncert-path = \"\"\nkey-path = \"\"\nredact-info-log = true\n\n")
	b.WriteString("[checkpoint]\nenable = true\nschema = \"tidb_lightning_checkpoint\"\ndriver = \"file\"\ndsn = \"tidb-lightning-checkpoint.pb\"\nkeep-after-success = \"remove\"\n\n")
	b.WriteString("[conflict]\nstrategy = \"\"\nprecheck-conflict-before-import = false\n# threshold = 10000\n# max-record-rows = 10000\n\n")
	b.WriteString("[tikv-importer]\nbackend = " + q(backend) + "\n")
	if backend == "local" {
		b.WriteString("sorted-kv-dir = " + q(sortedKVDir) + "\n")
	} else {
		b.WriteString("# sorted-kv-dir = \"/path/to/sorted-kv\" # required for backend=local\n")
	}
	b.WriteString("store-write-bwlimit = 0\nlogical-import-batch-size = \"96KiB\"\nlogical-import-batch-rows = 65536\nlogical-import-prep-stmt = false\n\n")
	b.WriteString("[mydumper]\nread-block-size = \"64KiB\"\nbatch-import-ratio = 0.75\ndata-source-dir = " + q(dataDir) + "\nno-schema = false\ncharacter-set = \"auto\"\ndata-character-set = \"binary\"\ncase-sensitive = false\nstrict-format = false\ndefault-file-rules = true\nfilter = [\"*.*\", \"!mysql.*\", \"!sys.*\"]\n\n")
	b.WriteString("[mydumper.csv]\nseparator = \",\"\ndelimiter = \"\\\"\"\nterminator = \"\"\nheader = true\nnot-null = false\nnull = \"\\\\N\"\nbackslash-escape = true\n\n")
	b.WriteString("[tidb]\nhost = " + q(host) + "\nport = " + strconv.Itoa(port) + "\nuser = " + q(user) + "\npassword = " + q(password) + "\nstatus-port = " + strconv.Itoa(statusPort) + "\n")
	if backend == "local" {
		b.WriteString("pd-addr = " + q(pdAddr) + "\n")
	} else {
		b.WriteString("# pd-addr = \"127.0.0.1:2379\" # required for backend=local\n")
	}
	b.WriteString("log-level = \"error\"\ntls = \"false\"\nmax-allowed-packet = 0\n\n")
	b.WriteString("[tidb.security]\n# TLS example: set these paths when TLS is enabled.\nca-path = \"\"\ncert-path = \"\"\nkey-path = \"\"\n\n")
	b.WriteString("[post-restore]\nchecksum = \"required\"\nanalyze = \"optional\"\nlevel-1-compact = false\ncompact = false\npost-process-at-last = true\n\n")
	b.WriteString("[cron]\nswitch-mode = \"5m\"\nlog-progress = \"5m\"\ncheck-disk-quota = \"1m\"\n")
	return b.String()
}

func Load(path string) (Config, string, error) {
	var cfg Config
	abs, err := filepath.Abs(path)
	if err != nil {
		return cfg, "", err
	}
	_, err = toml.DecodeFile(abs, &cfg)
	return cfg, abs, err
}

var passwordLine = regexp.MustCompile(`(?m)^(\s*password\s*=\s*).*?$`)

func Redact(text string) string { return passwordLine.ReplaceAllString(text, `${1}"******"`) }

func Status(logPath string) (string, error) {
	b, err := os.ReadFile(logPath)
	if errors.Is(err, os.ErrNotExist) {
		return "not-started", nil
	}
	if err != nil {
		return "", err
	}
	s := strings.ToLower(string(b))
	if strings.Contains(s, "the whole procedure completed") {
		return "succeeded", nil
	}
	if strings.Contains(s, "tidb lightning exit") || strings.Contains(s, "fatal") || strings.Contains(s, " error") || strings.Contains(s, "failed") {
		return "failed-or-incomplete", nil
	}
	return "running-or-interrupted", nil
}

func Resolve(binary, toolkitDir string, cfg config.File) (Invocation, error) {
	if binary != "" {
		path, err := validBinary(binary)
		return Invocation{Path: path}, err
	}
	for _, dir := range []string{toolkitDir, os.Getenv("TIDB_TOOLKIT_DIR"), cfg.Tools.TiDBToolkitDir} {
		if dir == "" {
			continue
		}
		path, err := findToolkit(dir)
		if err != nil {
			return Invocation{}, err
		}
		return Invocation{Path: path}, nil
	}
	if path, err := exec.LookPath("tidb-lightning"); err == nil {
		path, err = validBinary(path)
		return Invocation{Path: path}, err
	}
	if path, err := exec.LookPath("tiup"); err == nil {
		path, err = validBinary(path)
		return Invocation{Path: path, Args: []string{"tidb-lightning"}}, err
	}
	return Invocation{}, errors.New("tidb-lightning was not found; pass --binary, pass --toolkit-dir, set TIDB_TOOLKIT_DIR, configure tools.tidb-toolkit-dir, add tidb-lightning to PATH, or install tiup separately")
}

func validBinary(candidate string) (string, error) {
	if strings.HasSuffix(strings.ToLower(candidate), ".exe") {
		return "", fmt.Errorf("refusing Windows .exe in WSL: %s", candidate)
	}
	if !strings.ContainsAny(candidate, `/\\`) {
		path, err := exec.LookPath(candidate)
		if err != nil {
			return "", fmt.Errorf("executable %q not found: %w", candidate, err)
		}
		candidate = path
	}
	abs, err := filepath.Abs(candidate)
	if err != nil {
		return "", err
	}
	if strings.HasSuffix(strings.ToLower(abs), ".exe") {
		return "", fmt.Errorf("refusing Windows .exe in WSL: %s", abs)
	}
	info, err := os.Stat(abs)
	if err != nil {
		return "", err
	}
	if !info.Mode().IsRegular() {
		return "", fmt.Errorf("%s is not a regular file", abs)
	}
	if info.Mode()&0111 == 0 {
		return "", fmt.Errorf("%s is not executable", abs)
	}
	return abs, nil
}

func findToolkit(dir string) (string, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return "", err
	}
	info, err := os.Stat(abs)
	if err != nil {
		return "", fmt.Errorf("toolkit directory %q: %w", abs, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("toolkit path %q is not a directory", abs)
	}
	var matches, invalid []string
	err = filepath.WalkDir(abs, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		name := strings.ToLower(entry.Name())
		if name != "tidb-lightning" && name != "tidb-lightning.exe" {
			return nil
		}
		if name == "tidb-lightning.exe" {
			invalid = append(invalid, path+" (Windows .exe is not allowed in WSL)")
			return nil
		}
		p, validErr := validBinary(path)
		if validErr != nil {
			invalid = append(invalid, validErr.Error())
			return nil
		}
		matches = append(matches, p)
		return nil
	})
	if err != nil {
		return "", err
	}
	sort.Strings(matches)
	sort.Strings(invalid)
	if len(invalid) > 0 {
		return "", fmt.Errorf("invalid tidb-lightning candidate(s) in %s:\n%s", abs, strings.Join(invalid, "\n"))
	}
	if len(matches) == 0 {
		return "", fmt.Errorf("no executable tidb-lightning found under %s; unpack the Linux toolkit or pass --binary", abs)
	}
	if len(matches) > 1 {
		return "", fmt.Errorf("multiple tidb-lightning candidates found under %s; choose one with --binary:\n%s", abs, strings.Join(matches, "\n"))
	}
	return matches[0], nil
}

func Run(inv Invocation, configPath string, extra []string, stdin io.Reader, stdout, stderr io.Writer) error {
	args := append(append([]string{}, inv.Args...), "--config", configPath)
	args = append(args, extra...)
	cmd := exec.Command(inv.Path, args...)
	cmd.Stdin, cmd.Stdout, cmd.Stderr = stdin, stdout, stderr
	return cmd.Run()
}

